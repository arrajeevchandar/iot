"""Generate a browser-importable sketch from the modular source, excluding secrets."""
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]


def export():
    headers = ["config.h", "system_state.h", "sensor_manager.h", "actuator_manager.h", "automation_manager.h",
               "energy_manager.h", "tinyml_manager.h", "cloud_manager.h", "classroom_model.h"]
    sources = ["sensor_manager.cpp", "actuator_manager.cpp", "tinyml_manager.cpp", "cloud_manager.cpp", "main.cpp"]
    blocks = ["// GENERATED by scripts/export_wokwi.py. Edit modular firmware/, then regenerate.\n#include <Arduino.h>\n"]
    for folder, files in [("include", headers), ("src", sources)]:
        for name in files:
            data = (ROOT / "firmware" / folder / name).read_text()
            data = re.sub(r'^#pragma once\s*$', '', data, flags=re.M)
            data = re.sub(r'^#include "(?:' + '|'.join(re.escape(x) for x in headers) + r')"\s*$', '', data, flags=re.M)
            blocks.append(f"\n// ---- {folder}/{name} ----\n{data}")
    (ROOT / "wokwi/sketch.ino").write_text("\n".join(blocks))
    (ROOT / "wokwi/secrets.example.h").write_text((ROOT / "firmware/include/secrets.example.h").read_text())
    print("Wokwi browser sketch regenerated; no private credentials included.")


if __name__ == "__main__":
    export()
