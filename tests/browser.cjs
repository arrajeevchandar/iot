const assert = require('node:assert/strict');
const fs = require('node:fs');
const {chromium: playwright} = require('playwright');
const chromium = require('@sparticuz/chromium').default;

(async () => {
  const browser = await playwright.launch({executablePath:await chromium.executablePath(),args:chromium.args,headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1100}});
  const errors = [];
  page.on('pageerror',e=>errors.push(e.message));
  const waitText = (id,value) => page.waitForFunction(([id,value])=>document.getElementById(id).textContent.includes(value),[id,value],{timeout:12000});
  await page.goto(process.env.TEST_BASE_URL || 'http://127.0.0.1:8000');
  await waitText('connection','Live');
  await page.locator('[data-preset="empty"]').click();
  await page.locator('#auto-mode').click();
  await waitText('power','0');
  await page.locator('[data-preset="dark"]').click();
  await waitText('power','40');
  assert(await page.locator('#light1').isChecked());
  await page.locator('[data-preset="hot"]').click();
  await waitText('power','60');
  assert(await page.locator('#fan').isChecked());
  await page.locator('[data-preset="danger"]').click();
  await waitText('alert','CRITICAL');
  await waitText('servo-value','180');
  await page.locator('#reset').click();
  await waitText('command-status','Alarm active');
  await waitText('alert','CRITICAL');
  await page.locator('[data-preset="normal"]').click();
  await waitText('alert','INFO');
  await page.locator('#manual-mode').click();
  await waitText('mode-help','Manual controls');
  await page.locator('#light1').check();
  await waitText('command-status','acknowledged');
  await waitText('power','20');
  await page.locator('#servo').fill('75');
  await page.locator('#servo').dispatchEvent('change');
  await waitText('command-status','acknowledged');
  await waitText('servo-value','75');
  await page.locator('#auto-mode').click();
  await waitText('mode-help','Automatic rules');
  await waitText('power','0');
  await page.locator('#chart-metric').selectOption('energy_wh');
  await waitText('chart-name','Energy');
  await page.locator('[data-preset="dark"]').click();
  await waitText('power','40');
  fs.mkdirSync('screenshots',{recursive:true});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'screenshots/dashboard-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'screenshots/dashboard-mobile.png',fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile horizontal overflow');
  assert.deepEqual(errors,[],'Browser JavaScript errors');
  console.log('Browser passed: live telemetry, empty/dark/hot/danger, active-alarm reset, manual acknowledgement, servo, AUTO return, energy chart, mobile layout.');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
