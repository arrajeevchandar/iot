"""Convert the trained binary to an aligned flash-resident C++ array."""
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]


def convert():
    data = (ROOT / "tinyml/models/classroom_model.tflite").read_bytes()
    if data[4:8] != b"TFL3":
        raise ValueError("Not a TensorFlow Lite flatbuffer")
    lines = [", ".join(f"0x{b:02x}" for b in data[i:i+12]) for i in range(0, len(data), 12)]
    text = "#pragma once\n#include <cstdint>\n// Generated by tinyml/convert_model.py; do not edit.\n"
    text += "alignas(16) const unsigned char classroom_model[] = {\n  " + ",\n  ".join(lines) + "\n};\n"
    text += f"constexpr unsigned int classroom_model_len = {len(data)};\n"
    (ROOT / "firmware/include/classroom_model.h").write_text(text)
    print(f"Embedded {len(data)} verified TFLite bytes")


if __name__ == "__main__":
    convert()
